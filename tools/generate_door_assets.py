#!/usr/bin/env python3
"""Convert retained Figma V4 assets to flash-resident LVGL 8 RGB565 resources.

Run with the IDF Python environment (Pillow and CairoSVG). SVG root dimensions
are retained. Only the wallpaper receives the design's centred object-cover
crop. No video/demo photograph is embedded. This is an asset generator, not a
firmware build or a runtime screenshot renderer.
"""
from __future__ import annotations

import hashlib
import argparse
import io
import json
import xml.etree.ElementTree as ET
from pathlib import Path

import cairosvg
from PIL import Image, ImageDraw, ImageOps, __version__ as PILLOW_VERSION

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "components/starter_product/assets/door-v4"
SRC = ROOT / "components/starter_product/src"


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def rgb565(image: Image.Image, alpha: bool = False) -> bytes:
    out = bytearray()
    for r, g, b, a in image.convert("RGBA").getdata():
        value = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        out.extend((value & 255, value >> 8))
        if alpha:
            out.append(a)
    return bytes(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--preview-dir", type=Path, help="Optional local asset-only proof directory")
    args = parser.parse_args()
    manifest = dict(generator="tools/generate_door_assets.py",
                    format="LVGL 8, LV_COLOR_DEPTH=16, LV_COLOR_16_SWAP=0",
                    pillow=PILLOW_VERSION, cairosvg=cairosvg.__version__,
                    wallpaper=dict(), icons=[])
    original = (ASSETS / "wallpaper.png").read_bytes()
    image = Image.open(io.BytesIO(original)).convert("RGB")
    size = image.size
    wallpaper = ImageOps.fit(image, (1024, 600), Image.Resampling.LANCZOS, centering=(0.5, 0.5))
    data = rgb565(wallpaper)
    (ASSETS / "door_v4_wallpaper.rgb565").write_bytes(data)
    manifest["wallpaper"] = dict(original="wallpaper.png", source_size=size, sha256=digest(original),
        generated="door_v4_wallpaper.rgb565", width=1024, height=600, bytes=len(data),
        output_sha256=digest(data), crop="centred object-cover, no readability overlay baked in")
    header = ['/* Generated by tools/generate_door_assets.py. */', '#pragma once', '#include "lvgl.h"',
              '#if LV_COLOR_DEPTH != 16 || LV_COLOR_16_SWAP != 0',
              '#error "Door assets require native little-endian RGB565"', '#endif']
    code = ['/* Generated from retained Figma V4 SVGs; see assets/door-v4/README.md. */',
            '#include "door_v4_assets.h"']
    pixel_symbols = {}
    atlas = Image.new("RGB", (900, 720), "#0B0E10") if args.preview_dir else None
    for path in sorted(ASSETS.glob("*.svg")):
        raw = path.read_bytes()
        root = ET.fromstring(raw)
        w, h = int(root.attrib["width"]), int(root.attrib["height"])
        png = cairosvg.svg2png(bytestring=raw)
        rgba = Image.open(io.BytesIO(png)).convert("RGBA")
        if rgba.size != (w, h) or not rgba.getchannel("A").getbbox():
            raise ValueError(f"Invalid SVG output dimensions/content: {path.name}")
        pixels = rgb565(rgba, alpha=True)
        name = "door_asset_" + path.stem.replace("-", "_")
        header.append(f"LV_IMG_DECLARE({name});")
        pixel_key = (w, h, digest(pixels))
        if pixel_key not in pixel_symbols:
            pixel_symbols[pixel_key] = f"{name}_pixels"
            code.append(f"static const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST uint8_t {name}_pixels[] = {{")
            for offset in range(0, len(pixels), 18):
                code.append("    " + ", ".join(f"0x{x:02x}" for x in pixels[offset:offset + 18]) + ",")
            code.append("};")
        data_symbol = pixel_symbols[pixel_key]
        code.extend([f"const lv_img_dsc_t {name} = {{",
            f"    .header = {{.cf = LV_IMG_CF_TRUE_COLOR_ALPHA, .w = {w}, .h = {h}}},",
            f"    .data_size = sizeof({data_symbol}), .data = {data_symbol},", "};"])
        manifest["icons"].append(dict(original=path.name, sha256=digest(raw), symbol=name,
            width=w, height=h, bytes=len(pixels), data_symbol=data_symbol, rgb565a_sha256=digest(pixels)))
        if atlas:
            index = len(manifest["icons"]) - 1
            x, y = index % 6 * 150, index // 6 * 144
            atlas.paste(rgba, (x + (150 - w) // 2, y + 12), rgba)
            draw = ImageDraw.Draw(atlas)
            draw.text((x + 4, y + 94), path.stem.replace("-", "\n", 1), fill="white")
    for name, content in [("door_v4_assets.h", header), ("door_v4_assets.c", code)]:
        (SRC / name).write_text("\n".join(content) + "\n", encoding="utf-8", newline="\n")
    manifest["unique_icon_pixel_bytes"] = sum(w * h * 3 for w, h, _ in pixel_symbols)
    (ASSETS / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    if atlas:
        args.preview_dir.mkdir(parents=True, exist_ok=True)
        atlas.save(args.preview_dir / "icon-atlas.png")
    print(f"Wallpaper: {len(data)} B; {len(manifest['icons'])} exact-size icons; no runtime decoder/allocation.")


if __name__ == "__main__":
    main()
